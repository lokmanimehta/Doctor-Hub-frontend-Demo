export const getDayOfYear = (date = new Date()) => {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const difference = date - startOfYear;

  return Math.floor(difference / 86400000);
};

export const getDailyWellnessTip = (date = new Date()) => {
  const dayOfYear = getDayOfYear(date);
  const totalTips = dailyWellnessTips.length;
  const normalizedDay = ((dayOfYear - 1) % totalTips) + 1;
  const tip = dailyWellnessTips[normalizedDay - 1];

  return {
    ...tip,
    dayNumber: normalizedDay,
    totalTips
  };
};

export const getPatientWellnessDay = (
  accountCreatedAt,
  currentDate = new Date()
) => {
  if (!accountCreatedAt) {
    return 1;
  }

  const createdDate = new Date(Number(accountCreatedAt));

  if (Number.isNaN(createdDate.getTime())) {
    return 1;
  }

  const startOfCreatedDay = new Date(
    createdDate.getFullYear(),
    createdDate.getMonth(),
    createdDate.getDate()
  );

  const startOfCurrentDay = new Date(
    currentDate.getFullYear(),
    currentDate.getMonth(),
    currentDate.getDate()
  );

  const differenceInMs = startOfCurrentDay - startOfCreatedDay;
  const differenceInDays = Math.floor(differenceInMs / 86400000);

  return Math.max(differenceInDays + 1, 1);
};

export const getPatientDailyWellnessTip = (
  accountCreatedAt,
  currentDate = new Date()
) => {
  const patientDayNumber = getPatientWellnessDay(accountCreatedAt, currentDate);
  const totalTips = dailyWellnessTips.length;
  const tipIndex = (patientDayNumber - 1) % totalTips;
  const tip = dailyWellnessTips[tipIndex];

  return {
    ...tip,
    dayNumber: patientDayNumber,
    totalTips
  };
};